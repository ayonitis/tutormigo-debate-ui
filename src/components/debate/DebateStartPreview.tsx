import { Bot, User } from "lucide-react";
import { PositionBadge } from "@/components/ui/PositionBadge";
import type { DebateSetup } from "@/lib/debate/types";
import { findGrade, findLength, getTopicText, getTutorSide } from "@/lib/debate/validation";

interface DebateStartPreviewProps {
  setup: DebateSetup;
}

export function DebateStartPreview({ setup }: DebateStartPreviewProps) {
  const topic = getTopicText(setup);
  const grade = findGrade(setup.grade);
  const length = findLength(setup.length);
  const tutorSide = setup.side ? getTutorSide(setup.side) : null;

  return (
    <div className="space-y-4">
      <div>
        <p className="text-xs font-semibold uppercase tracking-wide text-muted">Topic</p>
        <p className="mt-0.5 break-words text-lg font-bold leading-snug">
          &ldquo;{topic}&rdquo;
        </p>
        <ul className="mt-2.5 flex flex-wrap gap-2 text-xs font-semibold text-ink">
          {grade && (
            <li className="rounded-full bg-inset px-3 py-1">
              Grades {grade.label} · {grade.name}
            </li>
          )}
          <li className="rounded-full bg-inset px-3 py-1">
            {length.title} · {length.demoRounds} rounds (demo)
          </li>
          <li className="rounded-full bg-inset px-3 py-1">
            Voice match: {setup.voiceMatch ? "On" : "Off"}
          </li>
        </ul>
      </div>

      <div className="grid gap-2 sm:grid-cols-2">
        {setup.side && (
          <div className="flex items-center justify-between gap-2 rounded-xl bg-elevated p-3">
            <span className="flex items-center gap-2 text-sm font-bold">
              <User className="size-4" aria-hidden="true" /> You
            </span>
            <PositionBadge side={setup.side} />
          </div>
        )}
        {tutorSide && (
          <div className="flex items-center justify-between gap-2 rounded-xl bg-elevated p-3">
            <span className="flex items-center gap-2 text-sm font-bold">
              <Bot className="size-4" aria-hidden="true" /> AI Tutor
            </span>
            <PositionBadge side={tutorSide} />
          </div>
        )}
      </div>

      <div className="rounded-2xl border border-line bg-white p-4">
        <p className="flex items-center gap-2 text-xs font-semibold uppercase tracking-wide text-brand-700">
          <Bot className="size-4" aria-hidden="true" />
          AI Tutor · sample message
        </p>
        <p className="mt-2 text-base">
          Welcome! I&apos;ll be arguing{" "}
          <strong>{tutorSide?.toUpperCase()}</strong> while you argue{" "}
          <strong>{setup.side?.toUpperCase()}</strong>. Whenever you&apos;re ready, share your
          opening argument and I&apos;ll respond.
        </p>
        <p className="mt-2 text-xs text-muted">
          Pre-written example for this demo — not generated by AI.
        </p>
      </div>
    </div>
  );
}
